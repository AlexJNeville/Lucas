def scrape_to_file(link_list, filename="data.txt"):
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
    }

    # Open the file in 'w' (write) mode with UTF-8 encoding for special characters
    with open(filename, "w", encoding="utf-8") as f:
        
        for url in link_list:
            print(f"Scraping: {url}...")
            f.write(f"{'='*50}\n")
            f.write(f"SOURCE: {url}\n")
            f.write(f"{'='*50}\n\n")

            try:
                response = requests.get(url, headers=headers, timeout=10)
                
                if response.status_code == 200:
                    content = trafilatura.extract(response.text)
                    if content:
                        f.write(content)
                    else:
                        f.write("Status: Success, but no main text content was found.")
                else:
                    f.write(f"Status: Failed (Error {response.status_code})")
            
            except Exception as e:
                f.write(f"Status: Error connecting - {str(e)}")

            f.write("\n\n\n") # Add space between entries
            time.sleep(1.5) # A slightly longer pause to be safe

    print(f"\nDone! All content has been saved to {filename}")

